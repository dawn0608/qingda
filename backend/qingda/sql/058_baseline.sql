CREATE VIEW messages WITH (security_invoker='true', security_barrier='true') AS
 SELECT m.id,
    m.event_id,
    m.account_id,
    m.conversation_id,
    m.platform_id,
    m.direction,
    m.source,
    m.msg_type,
    m.sender,
    m.created_at,
    m.received_at,
    m.content_id,
    m.outbound_task_id,
    m.metadata,
    COALESCE(c.text, t.content, ''::text) AS text
   FROM ((message_records m
     LEFT JOIN message_contents c ON ((c.id = m.content_id)))
     LEFT JOIN tasks t ON ((t.id = m.outbound_task_id)));

CREATE VIEW chat_history WITH (security_invoker='true', security_barrier='true') AS
 SELECT a.remark AS account_remark,
    a.nickname AS account_name,
    a.wxid AS account_wxid,
    c.kind,
    c.name AS conversation_name,
    c.peer_id,
    m.id,
    m.platform_id,
    m.direction,
    m.source,
    m.sender,
    m.msg_type,
    to_timestamp(m.created_at) AS message_time,
    to_timestamp(m.received_at) AS received_time,
    m.text,
    m.metadata,
    GREATEST(COALESCE(v.revoked, (0)::bigint), COALESCE(tv.revoked, (0)::bigint)) AS revoked,
    r.urls AS media_urls,
    r.state AS media_state,
    r.reason AS media_reason
   FROM (((((messages m
     JOIN accounts a ON ((a.id = m.account_id)))
     JOIN conversations c ON ((c.id = m.conversation_id)))
     LEFT JOIN message_views v ON ((v.source_id = m.id)))
     LEFT JOIN media_resources r ON ((r.message_id = m.id)))
     LEFT JOIN message_views tv ON ((tv.key = ('t:'::text || m.outbound_task_id))));

