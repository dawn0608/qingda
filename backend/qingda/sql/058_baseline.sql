CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

CREATE FUNCTION sync_primary_contact() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
 INSERT INTO user_contacts(user_id,channel,identifier) VALUES(NEW.id,NEW.channel,NEW.identifier)
 ON CONFLICT(user_id,channel) DO UPDATE SET identifier=excluded.identifier;
 RETURN NEW;
END $$;

